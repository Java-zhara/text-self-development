const articleContent = document.getElementById('articleContent');
const articleTitle = document.getElementById('articleTitle');
const articleBody = document.getElementById('articleBody');
const navTabs = document.querySelectorAll('.nav-tab');
const deckInfo = document.getElementById('deckInfo');

// ================================================================
// 4. ФУНКЦИЯ ОТОБРАЖЕНИЯ
// ================================================================
function renderCard(index) {
    const cardData = cards[index];
    if (!cardData) return;

    cardFrontTitle.textContent = cardData.title;
    cardImage.src = cardData.image;
    cardImage.alt = `Карточка ${index + 1}`;
    cardText.innerHTML = cardData.text;

    // Обновляем статью
    articleTitle.textContent = cardData.title;
    articleBody.innerHTML = cardData.textAll;

    currentIndexSpan.textContent = index + 1;
    totalCardsSpan.textContent = cards.length;
    progressText.textContent = `Прогресс: ${index + 1}/${cards.length}`;

    if (isFlipped) {
        card.classList.remove('flipped');
        isFlipped = false;
    }

    prevBtn.disabled = false;
    nextBtn.disabled = false;
}

// ================================================================
// 5. ПЕРЕКЛЮЧЕНИЕ РЕЖИМОВ
// ================================================================
function setMode(mode) {
    currentMode = mode;

    // Обновляем активную вкладку
    navTabs.forEach(tab => {
        tab.classList.toggle('active', tab.dataset.mode === mode);
    });

    // Переключаем класс на контейнере
    container.classList.toggle('article-mode', mode === 'articles');

    // Показываем/скрываем элементы
    if (mode === 'cards') {
        cardWrapper.style.display = 'block';
        document.querySelector('.controls').style.display = 'flex';
        document.querySelector('.counter').style.display = 'block';
        deckInfo.style.display = 'block';
        articleContent.style.display = 'none';
    } else {
        cardWrapper.style.display = 'none';
        document.querySelector('.controls').style.display = 'none';
        document.querySelector('.counter').style.display = 'none';
        deckInfo.style.display = 'none';
        articleContent.style.display = 'block';
    }
}

// ================================================================
// 6. ОБРАБОТЧИКИ
// ================================================================
// Переключение режимов по клику на вкладки
navTabs.forEach(tab => {
    tab.addEventListener('click', () => {
        setMode(tab.dataset.mode);
    });
});

// Переворот карточки
cardWrapper.addEventListener('click', () => {
    if (currentMode === 'cards') {
        card.classList.toggle('flipped');
        isFlipped = !isFlipped;
    }
});

flipBtn.addEventListener('click', (e) => {
    e.stopPropagation();
    if (currentMode === 'cards') {
        card.classList.toggle('flipped');
        isFlipped = !isFlipped;
    }
});

// Навигация
nextBtn.addEventListener('click', () => {
    currentIndex = (currentIndex + 1) % cards.length;
    renderCard(currentIndex);
});

prevBtn.addEventListener('click', () => {
    currentIndex = (currentIndex - 1 + cards.length) % cards.length;
    renderCard(currentIndex);
});

// Клавиатура
document.addEventListener('keydown', (e) => {
    if (currentMode === 'cards') {
        if (e.key === 'ArrowRight') {
            e.preventDefault();
            nextBtn.click();
        } else if (e.key === 'ArrowLeft') {
            e.preventDefault();
            prevBtn.click();
        } else if (e.key === ' ' || e.key === 'Space') {
            e.preventDefault();
            flipBtn.click();
        }
    } else {
        // В режиме статей стрелки тоже работают
        if (e.key === 'ArrowRight') {
            e.preventDefault();
            currentIndex = (currentIndex + 1) % cards.length;
            renderCard(currentIndex);
        } else if (e.key === 'ArrowLeft') {
            e.preventDefault();
            currentIndex = (currentIndex - 1 + cards.length) % cards.length;
            renderCard(currentIndex);
        }
    }
});

// ================================================================
// 7. ЗАПУСК
// ================================================================
renderCard(0);
setMode('cards');